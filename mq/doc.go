// Package mq 实现仅依赖本地文件与进程内并发的可靠消息投递与消费。
//
// 核心能力：
//   - 按路由键（routing key）发布与消费；同键严格有序，异键并行。
//   - 至少一次投递（at-least-once）：确认先 fsync 落盘才算成功。
//   - 显式确认（Ack）、拒绝（Nack）、可配置延期重试与死信隔离。
//   - 消费组：同组多消费者分担路由键（可扩容/缩容/再均衡），
//     不同消费组各自维护独立进度。
//   - 基于 WAL 的持久化与重启恢复；优雅关闭有界等待在途消息，
//     未确认消息重启后重投，已确认消息绝不重投。
//   - 按（消费组, 路由键）暂停 / 恢复投递（跨重启保留），
//     以及用于排障的路由键运行态快照（KeyStatus）。
//
// 典型用法见本目录的 Example 与 README.md。由于是至少一次语义，
// 业务处理器应当以 Message ID / 业务唯一键做幂等。
